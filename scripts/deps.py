#!/usr/bin/env python3
"""Check, install and update this repo's external dependencies from dependencies.toml (Linux, macOS, Windows).

    python scripts/deps.py list                    what the repo depends on
    python scripts/deps.py check                   installed? right version? do all pinned files agree?
    python scripts/deps.py check --pins-only       only the pin agreement (what CI runs)
    python scripts/deps.py install ID [ID ...]     install one dependency the right way for this OS
    python scripts/deps.py outdated                newest upstream version for every pinned dependency
    python scripts/deps.py verify-downloads        each platform's pinned GitHub-release build exists (network)
    python scripts/deps.py set-pin ID VERSION      move a pin everywhere it is written (configs + manifest)
    python scripts/deps.py docs [--check]          regenerate the register in docs/DEPENDENCIES.md

Standard library only, so it runs before the venv exists.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import platform
import re
import shlex
import shutil
import subprocess  # nosec B404 - runs commands named in the repo's own manifest
import sys
import tarfile
import tempfile
import tomllib
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "dependencies.toml"
DOCS = ROOT / "docs" / "DEPENDENCIES.md"
DOCS_START, DOCS_END = "<!-- deps:start (generated by scripts/deps.py docs) -->", "<!-- deps:end -->"
USER_AGENT = "automata-deps"


# ---------------------------------------------------------------- manifest

def load(path: Path = MANIFEST) -> dict:
    with path.open("rb") as fh:
        return tomllib.load(fh)


def deps_by_id(manifest: dict) -> dict[str, dict]:
    return {d["id"]: d for d in manifest["dependency"]}


def os_key(system: str | None = None) -> str:
    system = system or platform.system()
    return {"Linux": "linux", "Windows": "windows", "Darwin": "macos"}.get(system, system.lower())


def install_command(dep: dict, os_name: str | None = None) -> str | None:
    table = dep.get("install") or {}
    command = table.get(os_name or os_key()) or table.get("all")
    return command.replace("{version}", dep.get("pin", "")) if command else None


def version_tuple(text: str) -> tuple[int, ...]:
    return tuple(int(p) for p in re.findall(r"\d+", text)[:3])


# ---------------------------------------------------------------- pins

def pin_regex(pattern: str) -> re.Pattern:
    before, _, after = pattern.partition("{version}")
    return re.compile(re.escape(before) + r"([0-9A-Za-z][0-9A-Za-z.+_-]*)" + re.escape(after))


def pin_problems(dep: dict, root: Path = ROOT) -> list[str]:
    """Files that are missing, don't contain the pin, or contain a different version of it."""
    problems = []
    for entry in dep.get("pin_files", []):
        path = root / entry["file"]
        if not path.exists():
            problems.append(f"{entry['file']} is missing")
            continue
        pattern = entry.get("pattern")
        if not pattern:
            continue
        text = path.read_text(encoding="utf-8", errors="ignore")
        if "{version}" not in pattern:
            if pattern not in text:
                problems.append(f"{entry['file']} no longer contains {pattern}")
            continue
        pin = dep.get("pin", "")
        found = set(pin_regex(pattern).findall(text)) if pattern != "{version}" else ({pin} if pin in text else set())
        if pin not in found:
            problems.append(f"{entry['file']} does not pin {pattern.format(version=pin)}")
        others = sorted(found - {pin})
        if others:
            problems.append(f"{entry['file']} also has {', '.join(pattern.format(version=v) for v in others)}")
    return problems


def set_pin(dep_id: str, new: str, manifest_path: Path = MANIFEST, root: Path = ROOT) -> list[str]:
    manifest = load(manifest_path)
    dep = deps_by_id(manifest).get(dep_id)
    if not dep:
        raise SystemExit(f"deps: unknown id {dep_id}")
    old = dep.get("pin")
    if not old:
        raise SystemExit(f"deps: {dep_id} has no pin to move")
    changed = []
    for entry in dep.get("pin_files", []):
        pattern = entry.get("pattern")
        if not pattern or "{version}" not in pattern:
            continue
        path = root / entry["file"]
        text = path.read_text(encoding="utf-8")
        updated = text.replace(pattern.format(version=old), pattern.format(version=new))
        if updated != text:
            path.write_text(updated, encoding="utf-8")
            changed.append(entry["file"])
    text = manifest_path.read_text(encoding="utf-8")
    block = re.search(rf'(\[\[dependency\]\]\s*\nid = "{re.escape(dep_id)}".*?)(?=\n\[\[|\n\[[a-z]|\Z)', text, re.S)
    if not block:
        raise SystemExit(f"deps: could not find the {dep_id} block in {manifest_path.name}")
    new_block = block.group(1).replace(f'pin = "{old}"', f'pin = "{new}"', 1)
    manifest_path.write_text(text.replace(block.group(1), new_block, 1), encoding="utf-8")
    changed.append(manifest_path.name)
    return changed


# ---------------------------------------------------------------- presence

def run_check(dep: dict, os_name: str | None = None, release: dict | None = None) -> tuple[str, str]:
    """(state, detail): state is ok | missing | old | n/a."""
    os_name = os_name or os_key()
    command = dep.get(f"check_{os_name}") or dep.get("check")
    if dep["kind"] == "github-release":
        marker = Path.home() / f".{dep['id']}" / ".installed-version"
        installed = marker.read_text(encoding="utf-8").strip() if marker.exists() else None
        if not shutil.which(dep["id"]):
            return "missing", f"{dep['id']} not on PATH"
        expected = pin_for(dep, release)
        if installed and expected and installed != expected:
            return "old", f"installed {installed}, pinned {expected}"
        return "ok", installed or "installed (version unknown)"
    if not command:
        return "n/a", "no automatic check"
    exe = shutil.which(command[0])
    if not exe:
        return "missing", f"{command[0]} not on PATH"
    try:
        out = subprocess.run([exe, *command[1:]], cwd=ROOT, capture_output=True, text=True, timeout=60)  # nosec B603
    except (OSError, subprocess.TimeoutExpired) as exc:
        return "missing", str(exc)
    text = (out.stdout + out.stderr).strip()
    if out.returncode != 0:
        return "missing", text.splitlines()[-1] if text else f"exit {out.returncode}"
    if dep["kind"] == "python-lock":
        return "ok", "lockfile in sync with pyproject"
    match = re.search(dep["version_regex"], text) if dep.get("version_regex") else None
    version = match.group(1) if match else (text.splitlines()[0][:60] if text else "ok")
    if match and dep.get("min_version") and version_tuple(version) < version_tuple(dep["min_version"]):
        return "old", f"{version} < {dep['min_version']}"
    if match and dep.get("pin") and dep["kind"] in ("uv-tool",) and version != dep["pin"]:
        return "old", f"installed {version}, pinned {dep['pin']}"
    return "ok", version


# ---------------------------------------------------------------- github release installer

def pin_for(dep: dict, release: dict | None, plat: str | None = None) -> str:
    """The version this platform should run: a per-platform pin when a release lacks a build for it."""
    plat = plat or detect_platform()
    return ((release or {}).get("platform_pins") or {}).get(plat) or dep.get("pin", "")

def detect_platform(system: str | None = None, machine: str | None = None) -> str:
    system = system or platform.system()
    machine = (machine or platform.machine()).lower()
    arch = {"amd64": "x86_64", "x86_64": "x86_64", "arm64": "arm64", "aarch64": "arm64"}.get(machine, machine)
    return f"{os_key(system)}-{arch}"


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=120) as response:  # nosec B310 - https URLs from the manifest
        return response.read()


def pick_latest_release(releases: list[dict], asset_template: str) -> str | None:
    """Newest release tagged v* that ships the asset; skips website builds and other non-engine tags."""
    for release in releases:
        tag = release.get("tag_name", "")
        if not tag.startswith("v"):
            continue
        names = {a.get("name") for a in release.get("assets", [])}
        if asset_template.format(version=tag[1:]) in names:
            return tag[1:]
    return None


def extract(archive: Path, dest: Path) -> None:
    if archive.name.endswith(".zip"):
        root = dest.resolve()
        with zipfile.ZipFile(archive) as zf:
            for member in zf.infolist():  # refuse entries that would land outside dest (zip-slip)
                target = (root / member.filename).resolve()
                if target != root and root not in target.parents:
                    raise SystemExit(f"deps: {archive.name} has an unsafe path: {member.filename}")
            for member in zf.infolist():
                zf.extract(member, root)
        return
    with tarfile.open(archive) as tf:
        tf.extractall(dest, filter="data")


def add_to_windows_user_path(bin_dir: Path) -> bool:
    import ctypes
    import winreg

    with winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment", 0, winreg.KEY_READ | winreg.KEY_WRITE) as key:
        try:
            current, kind = winreg.QueryValueEx(key, "Path")
        except FileNotFoundError:
            current, kind = "", winreg.REG_EXPAND_SZ
        parts = [p for p in current.split(";") if p]
        if any(os.path.normcase(p.rstrip("\\")) == os.path.normcase(str(bin_dir)) for p in parts):
            return False
        winreg.SetValueEx(key, "Path", 0, kind, ";".join([str(bin_dir), *parts]))
    ctypes.windll.user32.SendMessageTimeoutW(0xFFFF, 0x001A, 0, "Environment", 0x0002, 5000, None)
    return True


def install_github_release(dep: dict, release: dict, version: str | None = None, skills: bool = True) -> None:
    plat = detect_platform()
    template = release["assets"].get(plat)
    if not template:
        raise SystemExit(f"deps: {dep['id']} has no build for {plat}")
    version = version or pin_for(dep, release, plat)
    asset = template.format(version=version)
    url = f"https://github.com/{release['repo']}/releases/download/v{version}/{asset}"
    prefix = Path.home() / f".{dep['id']}"
    print(f"deps: downloading {dep['id']} {version} ({plat})")
    data = fetch(url)
    want = fetch(url + ".sha256").decode().strip().split()[0].lower()
    if hashlib.sha256(data).hexdigest() != want:
        raise SystemExit(f"deps: checksum mismatch for {asset}")
    with tempfile.TemporaryDirectory(prefix=f"{dep['id']}-") as tmp_name:
        tmp = Path(tmp_name)
        (tmp / asset).write_bytes(data)
        extract(tmp / asset, tmp)
        unpacked = tmp / release.get("archive_root", dep["id"])
        prefix.mkdir(parents=True, exist_ok=True)
        for part in ("bin", "share"):  # replace the old install whole: a release's files go together
            shutil.rmtree(prefix / part, ignore_errors=True)
            if (unpacked / part).exists():
                shutil.move(str(unpacked / part), str(prefix / part))
    binary = release["binary"] + (".exe" if plat.startswith("windows") else "")
    if not (prefix / "bin" / binary).exists():
        raise SystemExit(f"deps: {asset} did not contain bin/{binary}")
    (prefix / ".installed-version").write_text(version, encoding="utf-8")
    print(f"deps: installed {dep['id']} {version} in {prefix}")

    bin_dir = prefix / "bin"
    if plat.startswith("windows"):
        if add_to_windows_user_path(bin_dir):
            print(f"deps: added {bin_dir} to your user PATH (open a new terminal)")
    else:
        link_dir = Path.home() / ".local" / "bin"
        link_dir.mkdir(parents=True, exist_ok=True)
        link = link_dir / release["binary"]
        if link.is_symlink() or link.exists():
            link.unlink()
        link.symlink_to(bin_dir / release["binary"])
        if plat.startswith("macos"):
            subprocess.run(["xattr", "-dr", "com.apple.quarantine", str(prefix)], check=False)  # nosec B603 B607
        print(f"deps: linked {link}")
        if str(link_dir) not in os.environ.get("PATH", "").split(os.pathsep):
            print(f"deps: add {link_dir} to PATH")

    skills_src = prefix / release["skills_dir"] if release.get("skills_dir") else None
    if skills and skills_src and skills_src.is_dir():
        dest = Path.home() / ".claude" / "skills"
        dest.mkdir(parents=True, exist_ok=True)
        for source in sorted(p for p in skills_src.iterdir() if p.is_dir()):
            shutil.rmtree(dest / source.name, ignore_errors=True)
            shutil.copytree(source, dest / source.name)
        print(f"deps: refreshed {dep['id']}'s agent skills in {dest}")


# ---------------------------------------------------------------- upstream versions

def latest_upstream(upstream: str, release: dict | None = None) -> str:
    source, _, name = upstream.partition(":")
    if source == "npm":
        return json.loads(fetch(f"https://registry.npmjs.org/{name}/latest"))["version"]
    if source == "pypi":
        return json.loads(fetch(f"https://pypi.org/pypi/{name}/json"))["info"]["version"]
    if source == "github-commit":
        return json.loads(fetch(f"https://api.github.com/repos/{name}/commits/HEAD"))["sha"]
    if source == "github-release":
        releases = json.loads(fetch(f"https://api.github.com/repos/{name}/releases?per_page=30"))
        if release:
            template = release["assets"].get(detect_platform()) or next(iter(release["assets"].values()))
            return pick_latest_release(releases, template) or "?"
        tags = [r["tag_name"] for r in releases if not r.get("prerelease")]
        return tags[0].lstrip("v") if tags else "?"
    raise ValueError(f"unknown upstream {upstream}")


# ---------------------------------------------------------------- docs

def render_docs(manifest: dict) -> str:
    lines = [DOCS_START, ""]
    categories: dict[str, list[dict]] = {}
    for dep in manifest["dependency"]:
        categories.setdefault(dep["category"], []).append(dep)
    for category, deps in categories.items():
        lines += [f"### {category}", "", "| Dependency | Needed for | Required | Version | Pinned in |", "|---|---|---|---|---|"]
        for dep in deps:
            unpinned = {"mcp-remote": "hosted by vendor", "browser": "per playwright version", "external-skills": "hashes in lock",
                        "ci-action": "tag in workflow", "python-lock": "lockfile", "node-lock": "lockfile"}
            version = dep.get("pin") or (f">= {dep['min_version']}" if dep.get("min_version") else
                                         unpinned.get(dep["kind"], "OS package manager"))
            if len(version) > 20:
                version = version[:12]
            files = [f"`{e['file']}`" for e in dep.get("pin_files", [])]
            if dep.get("pin"):
                files.append("`dependencies.toml`")
            files = ", ".join(files) or "-"
            lines.append(f"| **{dep['name']}** (`{dep['id']}`) | {dep['purpose']} | {'yes' if dep.get('required') else 'no'} | {version} | {files} |")
        lines.append("")
    lines += ["### Install, update, and what to do when it breaks", ""]
    for dep in manifest["dependency"]:
        lines.append(f"#### {dep['name']} (`{dep['id']}`)")
        commands = dep.get("install") or {}
        if commands:
            lines.append("- **Install:** " + "; ".join(f"{k}: `{v.replace('{version}', dep.get('pin', ''))}`" for k, v in commands.items()))
            if dep.get("install_note"):
                lines.append(f"  {dep['install_note']}")
        elif dep["kind"] == "github-release":
            lines.append(f"- **Install:** `python scripts/deps.py install {dep['id']}`")
        lines.append(f"- **Update:** {dep.get('update', '-')}")
        lines.append(f"- **If it breaks:** {dep.get('on_break', '-')}")
        lines.append("")
    lines.append(DOCS_END)
    return "\n".join(lines)


def write_docs(manifest: dict, check: bool = False) -> int:
    text = DOCS.read_text(encoding="utf-8")
    start, end = text.index(DOCS_START), text.index(DOCS_END) + len(DOCS_END)
    updated = text[:start] + render_docs(manifest) + text[end:]
    if check:
        if updated != text:
            print("deps: docs/DEPENDENCIES.md is out of date; run `python scripts/deps.py docs`")
            return 1
        print("deps: docs/DEPENDENCIES.md matches dependencies.toml")
        return 0
    DOCS.write_text(updated, encoding="utf-8")
    print(f"deps: wrote {DOCS.relative_to(ROOT)}")
    return 0


# ---------------------------------------------------------------- commands

def cmd_list(manifest: dict) -> int:
    for dep in manifest["dependency"]:
        version = dep.get("pin") or dep.get("min_version", "")
        print(f"{dep['id']:22} {dep['kind']:15} {'required' if dep.get('required') else 'optional':9} {version[:14]:14} {dep['purpose']}")
    return 0


def cmd_check(manifest: dict, pins_only: bool, only: list[str]) -> int:
    errors = 0
    for dep in manifest["dependency"]:
        if only and dep["id"] not in only:
            continue
        for problem in pin_problems(dep):
            print(f"PIN   {dep['id']:22} {problem}")
            errors += 1
        if pins_only:
            continue
        state, detail = run_check(dep, release=manifest.get("releases", {}).get(dep["id"]))
        if state == "ok":
            print(f"ok    {dep['id']:22} {detail}")
        elif state == "n/a":
            print(f"-     {dep['id']:22} {detail}")
        else:
            label = "FAIL " if dep.get("required") else "warn "
            errors += 1 if dep.get("required") else 0
            hint = install_command(dep) or f"python scripts/deps.py install {dep['id']}"
            print(f"{label} {dep['id']:22} {state}: {detail}  ->  {hint}")
    print(f"deps: {errors} problem(s)" + (" in pins" if pins_only else ""))
    return 1 if errors else 0


def cmd_install(manifest: dict, ids: list[str], version: str | None, skills: bool) -> int:
    deps = deps_by_id(manifest)
    for dep_id in ids:
        dep = deps.get(dep_id) or sys.exit(f"deps: unknown id {dep_id}")
        if dep["kind"] == "github-release":
            install_github_release(dep, manifest["releases"][dep_id], version, skills)
            continue
        command = install_command(dep)
        if not command:
            print(f"deps: {dep_id} has no install step on {os_key()} ({dep['kind']}); see docs/DEPENDENCIES.md")
            continue
        if command.startswith("manual:"):
            print(f"deps: {dep_id}: {command[7:].strip()}")
            continue
        venv_python = ROOT / ".venv" / ("Scripts/python.exe" if os_key() == "windows" else "bin/python")
        command = command.replace(".venv python", f'"{venv_python}"')
        print(f"deps: {dep_id}: {command}")
        result = subprocess.run(command, shell=True, cwd=ROOT)  # nosec B602 - command text comes from the repo manifest
        if result.returncode != 0:
            print(f"deps: {dep_id} install exited {result.returncode}")
            return result.returncode
    return 0


def cmd_verify_downloads(manifest: dict) -> int:
    """Every platform's pinned build of every GitHub-release tool exists (asset + checksum). Needs network."""
    problems = 0
    for dep in manifest["dependency"]:
        release = manifest.get("releases", {}).get(dep["id"])
        if dep["kind"] != "github-release" or not release:
            continue
        for plat, template in release["assets"].items():
            version = pin_for(dep, release, plat)
            url = f"https://github.com/{release['repo']}/releases/download/v{version}/{template.format(version=version)}"
            try:
                fetch(url + ".sha256")
                print(f"ok    {dep['id']:12} {plat:16} {version}")
            except Exception as exc:  # 404 or network
                problems += 1
                print(f"FAIL  {dep['id']:12} {plat:16} {version}: no build ({exc.__class__.__name__}); "
                      f"set [releases.{dep['id']}].platform_pins.{plat} to a version that has one")
    print(f"deps: {problems} missing build(s)")
    return 1 if problems else 0


def cmd_outdated(manifest: dict) -> int:
    for dep in manifest["dependency"]:
        if not dep.get("upstream"):
            continue
        try:
            latest = latest_upstream(dep["upstream"], manifest.get("releases", {}).get(dep["id"]))
        except Exception as exc:  # network or API errors: report and go on
            latest = f"? ({exc.__class__.__name__})"
        pin = dep.get("pin", "")
        state = "current" if not pin or latest.startswith(pin) or pin.startswith(latest) else "NEWER AVAILABLE"
        print(f"{dep['id']:22} pinned {pin[:14] or '-':14} latest {latest[:14]:14} {state if pin else ''}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("list")
    check = sub.add_parser("check")
    check.add_argument("--pins-only", action="store_true")
    check.add_argument("ids", nargs="*")
    install = sub.add_parser("install")
    install.add_argument("ids", nargs="+")
    install.add_argument("--version", help="install this version instead of the pin (github-release only)")
    install.add_argument("--no-skills", action="store_true")
    sub.add_parser("outdated")
    sub.add_parser("verify-downloads", help="check each platform's pinned GitHub-release build exists (network)")
    pin = sub.add_parser("set-pin")
    pin.add_argument("id")
    pin.add_argument("version")
    docs = sub.add_parser("docs")
    docs.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    manifest = load()
    if args.command == "list":
        return cmd_list(manifest)
    if args.command == "check":
        return cmd_check(manifest, args.pins_only, args.ids)
    if args.command == "install":
        return cmd_install(manifest, args.ids, args.version, not args.no_skills)
    if args.command == "outdated":
        return cmd_outdated(manifest)
    if args.command == "verify-downloads":
        return cmd_verify_downloads(manifest)
    if args.command == "set-pin":
        for name in set_pin(args.id, args.version):
            print(f"deps: updated {name}")
        print(f"deps: next: python scripts/deps.py check {args.id}, install/restart it, run its smoke test, commit")
        return 0
    return write_docs(manifest, args.check)


if __name__ == "__main__":
    sys.exit(main())
