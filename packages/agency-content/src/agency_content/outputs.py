"""Write content output as workspace JSON and a human-readable Markdown note."""
from __future__ import annotations

from pathlib import Path

from agency_common.models import ContentOutput
from agency_common.output_writer import OutputWriter
from agency_common.workspace import WorkspaceManager


def write_content_output(
    output: ContentOutput,
    workspace: WorkspaceManager,
    markdown_dir: Path | None = None,
    *,
    status: str = "draft",
) -> tuple[Path, Path | None]:
    """Write ContentOutput JSON to workspace and optional Markdown elsewhere."""
    json_path = workspace.write("content", output.brand_slug, output)

    md_path = None
    if markdown_dir:
        md_path = markdown_dir / f"{output.run_id}-content.md"
        md_content = _render_markdown(output)
        frontmatter = OutputWriter.standard_frontmatter(
            "content", output.brand_slug, output.run_id,
            tags=list({p.platform for p in output.pieces}),
            status=status,
        )
        OutputWriter.write_markdown(md_content, md_path, frontmatter)

    return json_path, md_path


def _render_markdown(output: ContentOutput) -> str:
    lines = [f"# Content Briefs: {output.brand_slug}", f"**Run ID**: {output.run_id}\n"]
    if output.summary:
        lines += [output.summary, ""]

    for piece in output.pieces:
        var = f" (Variation {piece.variation_index})" if len(output.pieces) > 1 else ""
        lines += [
            f"## {piece.platform.capitalize()} — {piece.content_type.replace('_', ' ').title()}{var}",
            f"**Topic**: {piece.topic}",
            "",
            piece.body,
            "",
        ]
        if piece.hashtags:
            lines.append(f"**Hashtags**: {' '.join(piece.hashtags)}")
        if piece.cta:
            lines.append(f"**CTA**: {piece.cta}")
        if piece.notes:
            lines.append(f"**Notes**: {piece.notes}")
        lines.append("")

    lines.append("---\n*Generated by Content Agent. Review and edit before publishing.*")
    return "\n".join(lines)
